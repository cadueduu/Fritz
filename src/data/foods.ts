/** The full TACO table (NEPA/UNICAMP, 597 foods), per 100 g. Generated by scripts/build-taco.mjs. */
export const TACO_FOODS: SearchFood[] = (tacoRows as [number, string, string, number, number, number, number, number][])
  .map(([, n, , kcal, p, c, g, f]) => ({ n, portion: '100 g', kcal, p, c, g, f, src: 'TACO' }));

const words = (s: string) => norm(s).replace(/[,()]/g, ' ').split(/\s+/).filter(Boolean);

/** Foods whose name contains every typed word, common portions first, then the TACO table. */
export const searchFoods = (query: string, limit = 20) => {
  const q = words(query);
  if (!q.length) return [];
  const hit = (f: SearchFood) => { const w = words(f.n).join(' '); return q.every(x => w.includes(x)); };
  return [...SEARCH.filter(hit), ...TACO_FOODS.filter(hit)].slice(0, limit);
};
